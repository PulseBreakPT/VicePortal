  for(const group of MASTER){
   if(set.has(key(group.id))&&matchesByGroup.get(group.id).has(n))add(group.id,matchesByGroup.get(group.id).get(n));
  }
  // These explicit source labels are meaningful only in their relevant record types.
  if(['Location','Collectible','Mission','Challenge','Equipment'].includes(entry.kind)&&aliases[n])add(...aliases[n]);
