export function applyProfileResearch(item) {
  const review = characterProfileResearch[item.id];
  if (!review) return item;
  const attributes = {...item.attributes};
  for (const [name,value] of Object.entries(review.fields)) {
    if (!attributes[name] || /^not verified/i.test(attributes[name])) attributes[name] = value;
  }
  if (!attributes['Biography availability'] || /^not verified/i.test(attributes['Biography availability'])) attributes['Biography availability'] = 'Documented partial context';
  const sources = [...(item.relatedSources || []), {label:'Supplemental gameplay profile',url:review.source}].filter((s,i,a)=>a.findIndex(x=>x.url===s.url)===i);
  return {...item,spoiler:true,attributes,paragraphs:[...new Set([...(item.paragraphs||[]),review.text])],relatedSources:sources};
}

