import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {quickDestinations,hubDestinations,primaryHubPaths} from '../src/components/homeContent.mjs';
import {cardSubtitle} from '../src/components/portal/catalogueModel.mjs';
import {splitDossier} from '../src/components/portal/dossier/dossierModel.mjs';
const mainNav=['/map','/story','/progress','/garage','/guides','/news'];
const editorial=['/experience','/videos/trailer-2','/regions','/characters','/screenshots'];
const paths=[...mainNav,...editorial,...primaryHubPaths,...quickDestinations.map(x=>x[1]),...hubDestinations.map(x=>x[4])];
assert.equal(new Set(paths).size,paths.length,'Repeated landing destination ownership');
assert.equal(quickDestinations.length,6);
assert.equal(hubDestinations.length,6);
const read=p=>readFile(new URL('../src/'+p,import.meta.url),'utf8');
const [app,hub,edition,stories,world,gallery,experience,sections]=await Promise.all(['App.js','components/TownHub.js','components/TownEdition.js','components/Stories.js','components/World.js','components/Gallery.js','components/RockstarExperience.js','data/sections.js'].map(read));
for(const path of paths)assert.ok(sections.includes("['"+path.slice(1)+"',")||path==='/videos/trailer-2','Unregistered landing path '+path);
assert.ok(!app.includes('<FreshLinks'));
assert.ok(!hub.includes('hub-map-open')&&!hub.includes('banner-explore-map'));
assert.ok(!stories.includes('characters-watch-trailer'));
assert.ok(!experience.includes('rs-poster-watch'));
assert.ok(edition.includes('home-experience-trailer'));
assert.ok(world.includes('marqueeWords')&&app.includes('<Marquee/>'));
assert.ok(gallery.includes('footer-disclaimer')&&!gallery.includes('NOT AFFILIATED WITH ROCKSTAR GAMES'));
for(const marker of ['<Hero','<QuickDestinations','<TownHub','<Wire','<ExperienceTeaser','<World','<Characters','<Gallery','<Footer','useCinematicEffects','useCardFlight',"import './Smooth.css'"])assert.ok(app.includes(marker),'Missing '+marker);
assert.equal(cardSubtitle({title:'Example',kind:'Vehicle',subtitle:'Progen · Supercars',category:'Supercars'},'Supercars',true),'Progen');
assert.equal(cardSubtitle({title:'Example',kind:'Weapon',category:'Handguns'},'Handguns',true),'');
assert.equal(cardSubtitle({title:'Example',kind:'Vehicle',subtitle:'Progen · Supercars',category:'Supercars'},'',true),'Progen · Supercars');
assert.equal(cardSubtitle({title:'Secret',kind:'Character',spoiler:true,subtitle:'Spoiler'},'',false),'Story details are hidden.');
const item={kind:'Character',title:'Example',description:'Original overview.',attributes:{Role:'Driver','Original credit':'Driver','Occupation / affiliation':'Driver',Damage:5,Range:5},source:'https://example.com'};
const view=splitDossier(item,true);
assert.equal(view.meta.attributes['Original credit'],undefined);
assert.equal(view.body.attributes.Role,'Driver');
assert.equal(view.body.attributes['Occupation / affiliation'],'Driver');
assert.equal(view.meta.attributes.Damage,5);
assert.equal(view.meta.attributes.Range,5);
console.log('Landing ownership, retained destinations, animation integration and scoped deduplication verified.');
