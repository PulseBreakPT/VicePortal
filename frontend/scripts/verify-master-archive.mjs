import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {MASTER,masterSections,archiveMembership,buildMaster,buildMusicRecords,buildVerifiedRecords} from '../src/data/masterArchive.mjs';
const read=p=>readFile(new URL('../src/data/'+p,import.meta.url),'utf8').then(JSON.parse);
const [snapshot,sources,verified]=await Promise.all(['universalSnapshot.json','universalSources.json','masterVerified.json'].map(read));
const sectionIds=new Set(masterSections.map(s=>s.id));
assert.equal(MASTER.length,32);
assert.equal(sectionIds.size,masterSections.length);
assert.ok(masterSections.every(s=>s.parent===null||sectionIds.has(s.parent)));
assert.equal(verified.rows.filter(x=>x.kind==='Animal').length,255);
assert.equal(verified.rows.filter(x=>x.kind==='Equipment').length,12);
assert.equal(new Set(verified.rows.map(x=>x.kind+'|'+x.title.toLowerCase())).size,267);
const seed=[{id:'a',kind:'Animal',title:'American Anhinga',category:'Birds',path:'/animals/a',collections:['animals'],source:'https://example.com',image:'old.webp',attributes:{Known:1}},{id:'b',kind:'Vehicle',title:'Car',path:'/vehicles/b',category:'Sports cars',collections:['vehicles/sports'],spoiler:true,attributes:{Speed:8}},{id:'c',kind:'Location',title:'Police station',category:'hotel',path:'/locations/c',collections:['locations'],attributes:{'Place type':'hotel'}}];
const before=JSON.stringify(seed);
const entries=buildMaster(seed,snapshot,sources,verified.rows);
assert.equal(JSON.stringify(seed),before);
assert.equal(entries.find(x=>x.id==='a').path,'/animals/a');
assert.equal(entries.find(x=>x.id==='a').image,'old.webp');
assert.equal(entries.filter(x=>x.kind==='Animal'&&x.title==='American Anhinga').length,1);
assert.ok(entries.find(x=>x.id==='b').collections.includes('archive/vehicles/sports-cars'));
assert.equal(entries.find(x=>x.id==='b').spoiler,true);
assert.ok(entries.find(x=>x.id==='c').collections.includes('archive/architecture/hotels'));
assert.ok(!entries.find(x=>x.id==='c').collections.includes('archive/architecture/police-stations'));
assert.ok(entries.filter(x=>x.kind==='Song').length>0);
assert.ok(entries.filter(x=>x.kind==='Song').every(x=>x.source.includes(sources.radio.sha)&&x.source.endsWith(sources.radio.trackPath)));
assert.ok(entries.filter(x=>x.kind==='Animal'&&x.category==='Catchable fish').every(x=>x.collections.includes('archive/wildlife/fish')));
assert.equal(new Set(entries.map(x=>x.id)).size,entries.length);
assert.equal(new Set(entries.map(x=>x.path)).size,entries.length);
assert.ok(entries.every(x=>x.collections.filter(c=>c.startsWith('archive')).every(c=>sectionIds.has(c))));
assert.equal(buildMaster(entries,snapshot,sources,verified.rows).length,entries.length);
assert.equal(buildMusicRecords({tracks:[{title:'Same',artist:'A',station:'One'},{title:'same',artist:'a',station:'Two'},{title:'Same',artist:'B',station:'One'}]},sources,[]).length,2);
assert.equal(buildVerifiedRecords(verified.rows,[]).length,267);
assert.equal(archiveMembership({kind:'Location',title:'A secret race',category:'Building',collections:['locations']}).includes('archive/racing'),false);
console.log('Master archive checks:',JSON.stringify({categories:MASTER.length,subcategories:masterSections.length-MASTER.length-1,sourceTrackRows:snapshot.tracks.length,uniqueMusic:entries.filter(x=>x.kind==='Song').length,reviewed:verified.rows.length}));
